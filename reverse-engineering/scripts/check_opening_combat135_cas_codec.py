def sha(path):
    with Path(path).open('rb')as stream:return hashlib.file_digest(stream,'sha256').hexdigest()
def save(path,value):path.write_text(json.dumps(value,indent=2,ensure_ascii=False)+'\n')
def packed(value):return(json.dumps(value,separators=(',',':'),ensure_ascii=False)+'\n').encode()
def metadata(path):return[json.loads(x)for x in path.read_bytes().splitlines()]
def write_metadata(path,rows):path.write_bytes(b''.join(packed(x)for x in rows))
def bounded_gzip(path):
    raw=path.read_bytes();assert len(raw)<=4194304
    decoder=zlib.decompressobj(31);value=decoder.decompress(raw,8*1024*1024+1)
    if len(value)>8*1024*1024 or decoder.unconsumed_tail or not decoder.eof or decoder.unused_data:raise ValueError('Review fixture gzip size/member/footer boundary')
    assert value.endswith(b'\n');return raw,value,value.splitlines(keepends=True)
def input_hashes():
    files=[PILOT/n for n in ('pilot.json','opening-combat135-cas-runtime.json','results.cas.jsonl.gz','blob-index.jsonl','blob-references.jsonl','output-only-adapter-proof.json')]
    files += list((PILOT/'cas-blobs').glob('*.json'))
